-- HyperMarket Cotonou — schéma PostgreSQL pour Supabase

CREATE TABLE IF NOT EXISTS users (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name       TEXT NOT NULL,
  email           TEXT UNIQUE NOT NULL,
  phone           TEXT,
  password_hash   TEXT NOT NULL,
  role            TEXT NOT NULL DEFAULT 'client',
  loyalty_credits INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS addresses (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label      TEXT NOT NULL,
  quarter    TEXT NOT NULL,
  details    TEXT,
  is_default SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS supermarkets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  address    TEXT NOT NULL,
  quarter    TEXT,
  hours      TEXT,
  logo_color TEXT DEFAULT '#1F4D3A',
  rating     REAL DEFAULT 4.5,
  is_active  SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS categories (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  icon TEXT
);

CREATE TABLE IF NOT EXISTS products (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supermarket_id INTEGER NOT NULL REFERENCES supermarkets(id) ON DELETE CASCADE,
  category_id    INTEGER REFERENCES categories(id),
  name           TEXT NOT NULL,
  brand          TEXT,
  description    TEXT,
  price          INTEGER NOT NULL,
  unit           TEXT DEFAULT 'unité',
  stock          INTEGER NOT NULL DEFAULT 0,
  image_emoji    TEXT DEFAULT '🛒',
  is_active      SMALLINT NOT NULL DEFAULT 1,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS promotions (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      TEXT NOT NULL,
  percent   INTEGER NOT NULL,
  scope     TEXT NOT NULL DEFAULT 'global',
  scope_id  INTEGER,
  active    SMALLINT NOT NULL DEFAULT 1,
  starts_at TIMESTAMPTZ,
  ends_at   TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS orders (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER NOT NULL REFERENCES users(id),
  subtotal         INTEGER NOT NULL,
  discount         INTEGER NOT NULL DEFAULT 0,
  delivery_fee     INTEGER NOT NULL DEFAULT 0,
  credits_used     INTEGER NOT NULL DEFAULT 0,
  total            INTEGER NOT NULL,
  status           TEXT NOT NULL DEFAULT 'en_attente',
  payment_method   TEXT NOT NULL,
  payment_status   TEXT NOT NULL DEFAULT 'en_attente',
  delivery_type    TEXT NOT NULL DEFAULT 'standard',
  delivery_quarter TEXT,
  delivery_slot    TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS order_items (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id   INTEGER NOT NULL REFERENCES products(id),
  product_name TEXT NOT NULL,
  unit_price   INTEGER NOT NULL,
  quantity     INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS notifications (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      TEXT NOT NULL,
  body       TEXT,
  type       TEXT DEFAULT 'info',
  is_read    SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_products_super ON products(supermarket_id);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id);
