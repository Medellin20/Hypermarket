-- HyperMarket Cotonou — schéma PostgreSQL pour Supabase

CREATE TABLE IF NOT EXISTS users (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name       TEXT NOT NULL,
  email           TEXT UNIQUE NOT NULL,
  phone           TEXT,
  password_hash   TEXT,
  auth_user_id    UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  role            TEXT NOT NULL DEFAULT 'client',
  loyalty_credits INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS addresses (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label      TEXT NOT NULL,
  quarter    TEXT NOT NULL,
  details    TEXT,
  is_default SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS supermarkets (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  address    TEXT NOT NULL,
  quarter    TEXT,
  hours      TEXT,
  logo_color TEXT DEFAULT '#1F4D3A',
  rating     REAL DEFAULT 4.5,
  is_active  SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS categories (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  icon TEXT
);

CREATE TABLE IF NOT EXISTS products (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supermarket_id INTEGER NOT NULL REFERENCES supermarkets(id) ON DELETE CASCADE,
  category_id    INTEGER REFERENCES categories(id),
  name           TEXT NOT NULL,
  brand          TEXT,
  description    TEXT,
  price          INTEGER NOT NULL,
  unit           TEXT DEFAULT 'unité',
  stock          INTEGER NOT NULL DEFAULT 0,
  image_emoji    TEXT DEFAULT '🛒',
  is_active      SMALLINT NOT NULL DEFAULT 1,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS promotions (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      TEXT NOT NULL,
  percent   INTEGER NOT NULL,
  scope     TEXT NOT NULL DEFAULT 'global',
  scope_id  INTEGER,
  active    SMALLINT NOT NULL DEFAULT 1,
  starts_at TIMESTAMPTZ,
  ends_at   TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS orders (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INTEGER NOT NULL REFERENCES users(id),
  subtotal         INTEGER NOT NULL,
  discount         INTEGER NOT NULL DEFAULT 0,
  delivery_fee     INTEGER NOT NULL DEFAULT 0,
  credits_used     INTEGER NOT NULL DEFAULT 0,
  total            INTEGER NOT NULL,
  status           TEXT NOT NULL DEFAULT 'en_attente',
  payment_method   TEXT NOT NULL,
  payment_status   TEXT NOT NULL DEFAULT 'en_attente',
  delivery_type    TEXT NOT NULL DEFAULT 'standard',
  delivery_quarter TEXT,
  delivery_slot    TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS order_items (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id     INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id   INTEGER NOT NULL REFERENCES products(id),
  product_name TEXT NOT NULL,
  unit_price   INTEGER NOT NULL,
  quantity     INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS notifications (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title      TEXT NOT NULL,
  body       TEXT,
  type       TEXT DEFAULT 'info',
  is_read    SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_products_super ON products(supermarket_id);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id);

ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE;

CREATE OR REPLACE FUNCTION add_user_address(
  p_user_id INTEGER,
  p_label TEXT,
  p_quarter TEXT,
  p_details TEXT,
  p_is_default BOOLEAN
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  inserted addresses;
BEGIN
  IF p_is_default THEN
    UPDATE addresses SET is_default = 0 WHERE user_id = p_user_id;
  END IF;

  INSERT INTO addresses (user_id, label, quarter, details, is_default)
  VALUES (p_user_id, p_label, p_quarter, p_details, CASE WHEN p_is_default THEN 1 ELSE 0 END)
  RETURNING * INTO inserted;
  RETURN to_jsonb(inserted);
END;
$$;

CREATE OR REPLACE FUNCTION create_order(
  p_user_id INTEGER,
  p_items JSONB,
  p_payment_method TEXT,
  p_delivery_type TEXT,
  p_delivery_quarter TEXT,
  p_delivery_slot TEXT,
  p_use_credits INTEGER
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  item RECORD;
  product_row products;
  customer users;
  order_id INTEGER;
  subtotal INTEGER := 0;
  discount INTEGER := 0;
  line_subtotal INTEGER;
  promo_percent INTEGER;
  loyalty_percent INTEGER;
  delivery_fee INTEGER;
  credits_used INTEGER;
  total INTEGER;
  earned INTEGER;
BEGIN
  FOR item IN
    SELECT product_id, SUM(quantity)::INTEGER AS quantity
    FROM jsonb_to_recordset(p_items) AS requested(product_id INTEGER, quantity INTEGER)
    GROUP BY product_id
    ORDER BY product_id
  LOOP
    SELECT * INTO product_row FROM products
    WHERE id = item.product_id AND is_active = 1 FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION USING ERRCODE = 'P1001', MESSAGE = format('Produit %s introuvable', item.product_id);
    END IF;
    IF product_row.stock < item.quantity THEN
      RAISE EXCEPTION USING ERRCODE = 'P1002',
        MESSAGE = format('Stock insuffisant pour « %s » (reste %s)', product_row.name, product_row.stock);
    END IF;

    SELECT COALESCE(MAX(percent), 0) INTO promo_percent
    FROM promotions
    WHERE active = 1 AND (
      scope = 'global'
      OR (scope = 'category' AND scope_id = product_row.category_id)
      OR (scope = 'supermarket' AND scope_id = product_row.supermarket_id)
    );
    line_subtotal := product_row.price * item.quantity;
    subtotal := subtotal + line_subtotal;
    discount := discount + ROUND(line_subtotal * promo_percent / 100.0);
  END LOOP;

  SELECT * INTO customer FROM users WHERE id = p_user_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION USING ERRCODE = 'P1001', MESSAGE = 'Utilisateur introuvable';
  END IF;
  SELECT LEAST(5, COUNT(*)::INTEGER / 5) INTO loyalty_percent
  FROM orders WHERE user_id = p_user_id AND status = 'livree';
  discount := discount + ROUND((subtotal - discount) * loyalty_percent / 100.0);
  delivery_fee := CASE p_delivery_type WHEN 'express' THEN 2000 WHEN 'retrait' THEN 0 ELSE 1000 END;
  credits_used := LEAST(GREATEST(COALESCE(p_use_credits, 0), 0), customer.loyalty_credits,
    GREATEST(subtotal - discount + delivery_fee, 0));
  total := subtotal - discount + delivery_fee - credits_used;
  earned := ROUND(subtotal * 0.01);

  INSERT INTO orders (
    user_id, subtotal, discount, delivery_fee, credits_used, total,
    payment_method, payment_status, delivery_type, delivery_quarter, delivery_slot, status
  ) VALUES (
    p_user_id, subtotal, discount, delivery_fee, credits_used, total,
    p_payment_method, CASE WHEN p_payment_method = 'cash' THEN 'en_attente' ELSE 'paye' END,
    p_delivery_type, p_delivery_quarter, p_delivery_slot, 'confirmee'
  ) RETURNING id INTO order_id;

  FOR item IN
    SELECT product_id, SUM(quantity)::INTEGER AS quantity
    FROM jsonb_to_recordset(p_items) AS requested(product_id INTEGER, quantity INTEGER)
    GROUP BY product_id
    ORDER BY product_id
  LOOP
    SELECT * INTO product_row FROM products WHERE id = item.product_id;
    INSERT INTO order_items (order_id, product_id, product_name, unit_price, quantity)
    VALUES (order_id, product_row.id, product_row.name, product_row.price, item.quantity);
    UPDATE products SET stock = stock - item.quantity WHERE id = item.product_id;
  END LOOP;

  UPDATE users SET loyalty_credits = loyalty_credits - credits_used + earned WHERE id = p_user_id;
  INSERT INTO notifications (user_id, title, body, type)
  VALUES (
    p_user_id,
    format('Commande #%s confirmée ✅', order_id),
    format('Total : %s FCFA. Vous avez gagné %s crédits fidélité.', to_char(total, 'FM999G999G999'), earned),
    'order'
  );
  RETURN jsonb_build_object('orderId', order_id, 'earned', earned);
END;
$$;

CREATE OR REPLACE FUNCTION cancel_order(p_order_id INTEGER, p_user_id INTEGER)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  order_row orders;
  item order_items;
BEGIN
  SELECT * INTO order_row FROM orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('status', 404, 'error', 'Commande introuvable');
  END IF;
  IF order_row.user_id <> p_user_id THEN
    RETURN jsonb_build_object('status', 403, 'error', 'Accès refusé');
  END IF;
  IF order_row.status IN ('en_livraison', 'livree', 'annulee') THEN
    RETURN jsonb_build_object('status', 409, 'error', 'Cette commande ne peut plus être annulée');
  END IF;

  FOR item IN SELECT * FROM order_items WHERE order_id = order_row.id LOOP
    UPDATE products SET stock = stock + item.quantity WHERE id = item.product_id;
  END LOOP;
  UPDATE orders SET status = 'annulee' WHERE id = order_row.id;
  INSERT INTO notifications (user_id, title, body, type)
  VALUES (order_row.user_id, format('Commande #%s annulée', order_row.id),
    'Votre commande a été annulée et le stock restauré.', 'order');
  RETURN jsonb_build_object('orderId', order_row.id);
END;
$$;

CREATE OR REPLACE FUNCTION reset_demo_data()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  TRUNCATE TABLE order_items, orders, notifications, promotions,
    products, categories, supermarkets, addresses, users RESTART IDENTITY CASCADE;
END;
$$;

CREATE OR REPLACE FUNCTION admin_dashboard_stats()
RETURNS JSONB
LANGUAGE SQL
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT jsonb_build_object(
    'stats', jsonb_build_object(
      'revenue', COALESCE((SELECT SUM(total) FROM orders WHERE status <> 'annulee'), 0),
      'orders', (SELECT COUNT(*) FROM orders),
      'pending', (SELECT COUNT(*) FROM orders
        WHERE status IN ('en_attente', 'confirmee', 'en_preparation', 'en_livraison')),
      'clients', (SELECT COUNT(*) FROM users WHERE role = 'client'),
      'products', (SELECT COUNT(*) FROM products WHERE is_active = 1),
      'outOfStock', (SELECT COUNT(*) FROM products WHERE stock = 0 AND is_active = 1)
    ),
    'byStatus', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('status', status, 'count', count))
      FROM (SELECT status, COUNT(*) AS count FROM orders GROUP BY status) AS grouped
    ), '[]'::JSONB),
    'topProducts', COALESCE((
      SELECT jsonb_agg(jsonb_build_object('product_name', product_name, 'qty', qty))
      FROM (
        SELECT product_name, SUM(quantity) AS qty
        FROM order_items GROUP BY product_name ORDER BY qty DESC LIMIT 5
      ) AS grouped
    ), '[]'::JSONB),
    'recentOrders', COALESCE((
      SELECT jsonb_agg(to_jsonb(recent))
      FROM (
        SELECT orders.*, users.full_name AS client_name
        FROM orders JOIN users ON users.id = orders.user_id
        ORDER BY orders.created_at DESC LIMIT 8
      ) AS recent
    ), '[]'::JSONB)
  );
$$;

